// Generated by `build.rs`: the single-file UI bundle, or an empty string when it was not built.
include!(concat!(env!("OUT_DIR"), "/ui.rs"));

pub type Body = BoxBody<Bytes, std::io::Error>;

/// Wraps plain bytes in the boxed body type the hyper service returns.
pub fn body_from(bytes: Bytes) -> Body {
    Full::new(bytes)
        .map_err(|never: Infallible| match never {})
        .boxed()
}

const DEFAULT_LIMIT: usize = 300;
const MAX_LIMIT: usize = 2000;

pub struct Ui {
    pub store: Arc<Store>,
    pub ca: Arc<Ca>,
    pub hosts: Vec<String>,
    pub port: u16,
    pub version: String,
    pub lang: Lang,
}

impl Ui {
    /// True when this request is addressed to the proxy's own UI (any local name, proxy port).
    pub fn serves(&self, host: &str, port: u16) -> bool {
        host_matches(&self.hosts, host, port, self.port)
    }

    /// Same question without the port, for requests a browser sends straight at
    /// the proxy (origin-form) instead of through it (absolute-form).
    pub fn serves_host(&self, host: &str) -> bool {
        host_is_local(&self.hosts, host)
    }

    pub async fn handle(self: Arc<Self>, mut req: Request<Incoming>) -> Response<Body> {
        let path = req.uri().path().to_string();
        if path == "/ws" && is_websocket(&req) {
            return self.upgrade_ws(&mut req);
        }

        let query = parse_query(req.uri().query().unwrap_or(""));
        let lang = lang_of(&req, &query, self.lang);
        let method = req.method().clone();

        match (method.clone(), path.as_str()) {
            (Method::GET, "/api/state") => json_ok(json!(self.store.stats())),
            (Method::GET, "/api/flows") => {
                let limit = number(&query, "limit", DEFAULT_LIMIT).clamp(1, MAX_LIMIT);
                let offset = number(&query, "offset", 0);
                let kind = text(&query, "kind").and_then(|k| Kind::parse(&k));
                let status = StatusFilter::parse(&text(&query, "status").unwrap_or_default());
                let order = if text(&query, "order").as_deref() == Some("desc") {
                    Order::Desc
                } else {
                    Order::Asc
                };
                let list_query = ListQuery {
                    limit,
                    offset,
                    order,
                    q: text(&query, "q"),
                    kind,
                    method: text(&query, "method"),
                    status,
                };
                let (total, flows) = self.store.list(&list_query);
                json_ok(json!({ "total": total, "flows": flows }))
            }
            (Method::DELETE, "/api/flows") => {
                self.store.clear();
                json_ok(json!({ "ok": true }))
            }
            (Method::POST, "/api/replay") => {
                let body = req
                    .into_body()
                    .collect()
                    .await
                    .map(|c| c.to_bytes())
                    .unwrap_or_default();
                if self.store.is_paused() {
                    return error(StatusCode::CONFLICT, i18n::replay_paused(lang));
                }
                let parsed = serde_json::from_slice::<Value>(&body)
                    .map_err(|e| e.to_string())
                    .and_then(|value| replay::Replay::parse(&value));
                match parsed {
                    Ok(replay) => match replay::send(self.store.clone(), self.port, replay).await {
                        Ok(id) => json_ok(json!({ "id": id })),
                        Err(e) => error(StatusCode::BAD_GATEWAY, i18n::replay_failed(lang, &e)),
                    },
                    Err(e) => error(StatusCode::BAD_REQUEST, i18n::replay_failed(lang, &e)),
                }
            }
            (Method::POST, "/api/pause") => {
                let body = req
                    .into_body()
                    .collect()
                    .await
                    .map(|c| c.to_bytes())
                    .unwrap_or_default();
                let requested = serde_json::from_slice::<Value>(&body)
                    .ok()
                    .and_then(|v| v.get("paused").and_then(|p| p.as_bool()));
                let paused = match requested {
                    Some(p) => p,
                    None => !self.store.is_paused(),
                };
                self.store.set_paused(paused);
                json_ok(json!({ "paused": paused }))
            }
            (Method::GET, "/api/export/har") => {
                let ids: Option<Vec<u64>> = text(&query, "ids").map(|ids| {
                    ids.split(',')
                        .filter_map(|id| id.trim().parse().ok())
                        .collect()
                });
                let all = self.store.list(&ListQuery {
                    limit: MAX_LIMIT,
                    offset: 0,
                    order: Order::Asc,
                    ..Default::default()
                });
                let mut flows = Vec::new();
                for summary in all.1 {
                    if let Some(ids) = &ids {
                        if !ids.contains(&summary.id) {
                            continue;
                        }
                    }
                    if let Some(flow) = self.store.get(summary.id) {
                        flows.push(flow);
                    }
                }
                let stamp = chrono::Local::now().format("%Y%m%d-%H%M%S");
                let body = serde_json::to_vec(&har::har(&flows, &self.version)).unwrap_or_default();
                Response::builder()
                    .status(StatusCode::OK)
                    .header(header::CONTENT_TYPE, "application/json; charset=utf-8")
                    .header(
                        header::CONTENT_DISPOSITION,
                        format!("attachment; filename=\"proxyhand-{stamp}.har\""),
                    )
                    .body(body_from(Bytes::from(body)))
                    .unwrap()
            }
            (Method::GET, "/api/ca.crt") | (Method::GET, "/api/ca.pem") => Response::builder()
                .status(StatusCode::OK)
                .header(header::CONTENT_TYPE, "application/x-x509-ca-cert")
                .header(
                    header::CONTENT_DISPOSITION,
                    "attachment; filename=\"proxyhand-ca.crt\"",
                )
                .body(body_from(Bytes::from(
                    self.ca.cert_pem().as_bytes().to_vec(),
                )))
                .unwrap(),
            (Method::GET, "/api/trust") => {
                let ca_path = self.store.stats().ca_path;
                let instructions = i18n::trust_instructions(lang, &ca_path);
                let fingerprint = self.ca.fingerprint();
                json_ok(json!({
                    "caPath": ca_path,
                    "fingerprint": fingerprint,
                    "instructions": instructions,
                }))
            }
            (method, path) if path.starts_with("/api/flows/") => {
                let id: u64 = path["/api/flows/".len()..].parse().unwrap_or(0);
                match method {
                    Method::GET => match self.store.get(id) {
                        Some(flow) => json_ok(json!(flow.dto(lang))),
                        None => error(StatusCode::NOT_FOUND, i18n::flow_not_found(lang)),
                    },
                    Method::DELETE => {
                        let removed = self.store.remove(id);
                        json_ok(json!({ "ok": removed }))
                    }
                    _ => error(
                        StatusCode::METHOD_NOT_ALLOWED,
                        i18n::no_route(lang, method.as_str(), path),
                    ),
                }
            }
            (Method::GET, path) if path.starts_with("/api/") => {
                error(StatusCode::NOT_FOUND, i18n::no_route(lang, "GET", path))
            }
            (Method::GET, _) => self.index(),
            _ => error(
                StatusCode::METHOD_NOT_ALLOWED,
                i18n::no_route(lang, method.as_str(), path.as_str()),
            ),
        }
    }

    fn index(&self) -> Response<Body> {
        if INDEX_HTML.is_empty() {
            return plain(
                StatusCode::INTERNAL_SERVER_ERROR,
                "proxyhand: web UI not built — run `pnpm install && pnpm build:web` first",
            );
        }
        Response::builder()
            .status(StatusCode::OK)
            .header(header::CONTENT_TYPE, "text/html; charset=utf-8")
            .header(header::CACHE_CONTROL, "no-store")
            .body(body_from(Bytes::from_static(INDEX_HTML.as_bytes())))
            .unwrap()
    }

    fn upgrade_ws(self: &Arc<Self>, req: &mut Request<Incoming>) -> Response<Body> {
        let key = req
            .headers()
            .get("sec-websocket-key")
            .and_then(|v| v.to_str().ok())
            .unwrap_or_default()
            .to_string();
        let accept = derive_accept_key(key.as_bytes());
        let upgrade = hyper::upgrade::on(req);
        let ui = self.clone();
        tokio::spawn(async move {
            if let Ok(upgraded) = upgrade.await {
                ui.ws_loop(upgraded).await;
            }
        });
        Response::builder()
            .status(StatusCode::SWITCHING_PROTOCOLS)
            .header(header::CONNECTION, "Upgrade")
            .header(header::UPGRADE, "websocket")
            .header("sec-websocket-accept", accept)
            .body(body_from(Bytes::new()))
            .unwrap()
    }

    async fn ws_loop(self: Arc<Self>, upgraded: Upgraded) {
        let mut ws =
            WebSocketStream::from_raw_socket(TokioIo::new(upgraded), Role::Server, None).await;
        let mut events = self.store.subscribe();
        let selected = Arc::new(AtomicU64::new(0));

        let hello = ServerEvent::Hello {
            state: self.store.stats(),
        };
        if !push(&mut ws, &hello).await {
            return;
        }

        // Coalesce stats so a burst of captured flows does not flood the socket.
        let mut stats_due: Option<Instant> = None;

        loop {
            let wake = stats_due.unwrap_or_else(|| Instant::now() + Duration::from_secs(3600));
            tokio::select! {
                incoming = ws.next() => {
                    match incoming {
                        None => break,
                        Some(Err(_)) => break,
                        Some(Ok(Message::Text(text))) => {
                            if let Ok(value) = serde_json::from_str::<Value>(text.as_str()) {
                                match value.get("t").and_then(|t| t.as_str()) {
                                    Some("select") => {
                                        let id = value.get("id").and_then(|i| i.as_u64()).unwrap_or(0);
                                        selected.store(id, Ordering::Relaxed);
                                    }
                                    Some("ping") => {
                                        let event = ServerEvent::Stats { stats: self.store.stats() };
                                        if !push(&mut ws, &event).await { break; }
                                    }
                                    _ => {}
                                }
                            }
                        }
                        Some(Ok(Message::Close(_))) | Some(Ok(Message::Ping(_))) | Some(Ok(Message::Pong(_))) => {}
                        Some(Ok(_)) => {}
                    }
                }
                event = events.recv() => {
                    match event {
                        Ok(event) => {
                            let forward = match &event {
                                ServerEvent::New { .. } | ServerEvent::Update { .. } => {
                                    stats_due = Some(Instant::now() + Duration::from_millis(250));
                                    true
                                }
                                ServerEvent::Sse { id, .. } | ServerEvent::Ws { id, .. } => {
                                    *id == selected.load(Ordering::Relaxed)
                                }
                                _ => true,
                            };
                            if forward && !push(&mut ws, &event).await {
                                break;
                            }
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Lagged(_)) => continue,
                        Err(tokio::sync::broadcast::error::RecvError::Closed) => break,
                    }
                }
                _ = tokio::time::sleep_until(wake) => {
                    if stats_due.is_some() {
                        stats_due = None;
                        let event = ServerEvent::Stats { stats: self.store.stats() };
                        if !push(&mut ws, &event).await { break; }
                    }
                }
            }
        }
    }
}

use futures_util::{SinkExt, StreamExt};

async fn push<S>(ws: &mut WebSocketStream<S>, event: &ServerEvent) -> bool
where
    S: tokio::io::AsyncRead + tokio::io::AsyncWrite + Unpin,
{
    let Ok(text) = serde_json::to_string(event) else {
        return true;
    };
    ws.send(Message::Text(text.into())).await.is_ok()
}

fn is_websocket(req: &Request<Incoming>) -> bool {
    req.headers()
        .get(header::UPGRADE)
        .and_then(|v| v.to_str().ok())
        .map(|v| v.eq_ignore_ascii_case("websocket"))
        .unwrap_or(false)
        && req.headers().contains_key("sec-websocket-key")
}

fn parse_query(query: &str) -> Vec<(String, String)> {
    url::form_urlencoded::parse(query.as_bytes())
        .map(|(k, v)| (k.into_owned(), v.into_owned()))
        .collect()
}

fn text(query: &[(String, String)], key: &str) -> Option<String> {
    query.iter().find(|(k, _)| k == key).map(|(_, v)| v.clone())
}

fn number(query: &[(String, String)], key: &str, fallback: usize) -> usize {
    text(query, key)
        .and_then(|v| v.trim().parse().ok())
        .unwrap_or(fallback)
}

fn lang_of(req: &Request<Incoming>, query: &[(String, String)], fallback: Lang) -> Lang {
    if let Some(lang) = text(query, "lang").as_deref().and_then(Lang::parse) {
        return lang;
    }
    req.headers()
        .get(header::ACCEPT_LANGUAGE)
        .and_then(|v| v.to_str().ok())
        .and_then(Lang::from_accept_language)
        .unwrap_or(fallback)
}

fn json_ok(value: Value) -> Response<Body> {
    let body = serde_json::to_vec(&value).unwrap_or_else(|_| b"{}".to_vec());
    Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, "application/json; charset=utf-8")
        .header(header::CACHE_CONTROL, "no-store")
        .body(body_from(Bytes::from(body)))
        .unwrap()
}

fn error(status: StatusCode, message: impl Into<String>) -> Response<Body> {
    let body = serde_json::to_vec(&json!({ "error": message.into() })).unwrap_or_default();
    Response::builder()
        .status(status)
        .header(header::CONTENT_TYPE, "application/json; charset=utf-8")
        .body(body_from(Bytes::from(body)))
        .unwrap()
}

fn plain(status: StatusCode, message: &str) -> Response<Body> {
    Response::builder()
        .status(status)
        .header(header::CONTENT_TYPE, "text/plain; charset=utf-8")
        .body(body_from(Bytes::from(message.to_string())))
        .unwrap()
}
